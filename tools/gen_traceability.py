#!/usr/bin/env python3
"""Generate the traceability matrix from the record, by executing it (B3, HUG-VER-001).

    python tools/gen_traceability.py              execute the suite, write the matrix
    python tools/gen_traceability.py --check      regenerate and diff, write nothing
    python tools/gen_traceability.py --self-test  the negative case per failure edge
    python tools/gen_traceability.py --run-record run.json   reuse a recorded run

The record names this file: `defs/requirements.yaml` says the matrix "is generated by
`tools/gen_traceability.py` from requirement IDs referenced in code and documents" and
that "hand-maintained matrices are prohibited."

WHAT MAKES A ROW EVIDENCE. HUG-VER-001 wants each requirement to reach a NEED upstream
and a verification reference downstream. The owner added the clause that does the work:
a row that cannot name an EXECUTED case is a FINDING, not a blank. So the downstream
cell is not filled from a scan of the source tree — it is filled from
`tools/verification_run.py`, which runs the cases and writes down which ones ran and how
they went. A matrix built by grepping would populate identically whether or not a single
test executed.

THE CLEAN FIRST RUN PROVES NOTHING, AND THAT IS THE DANGER. Measured against the record
as it stands: all 38 requirements reach a NEED, 37 of them directly; the only row needing
the parent-chain clause at all is HUG-EPS-004 (-> HUG-SYS-005 -> NEED-04); the parent
graph has three edges and no cycle; every one of the 11 CONOPS identifiers is cited. So
EVERY failure condition this generator is required to enforce has zero naturally
occurring instances, and a generator with all of them stubbed to `return True` would emit
a byte-identical matrix. That is why `--self-test` exists and why it is in the gate: the
conditions are demonstrated against synthesized inputs, because the record cannot
demonstrate them. HUG-VER-001 says so in its own last sentence — "Each specified failure
condition shall be demonstrated to fail generation (negative case) before a passing
matrix is accepted."

WHAT THIS DOES NOT DUPLICATE. `design_record_consistency.c3` already asserts NEED
reachability, CONOPS coverage and dangling-citation detection over the record's PROSE
(docs/conops.md, docs/requirements.md) as an order-independent fixed point. This
generator asserts the same properties over the SOURCE (`defs/requirements.yaml`) and adds
the downstream half, which C3 does not have. They are two halves, not two copies: C3
guards the documents a reader reads, B3 guards the spine the build generates from. The
fixed-point form here is deliberately C3's form, and the CONOPS definition set is read
through C3's own table parser rather than a second one — a fourth parser for the record's
table grammar is how two checks come to disagree about what a table is.
"""
import argparse
import difflib
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "tools"))
sys.path.insert(0, str(REPO / "tools" / "checkers"))

import hugdefs                                                       # noqa: E402
import verification_run                                              # noqa: E402
from design_record_consistency import _doc_rows                      # noqa: E402

OUT = REPO / "verification" / "TRACEABILITY.md"

CONOPS_ID = re.compile(r"NEED-\d{2}|CON-\d{2}|ASM-\d{2}")

#: Every failure condition HUG-VER-001 specifies, plus the owner's addition (F5).
#: Each MUST have a demonstrated negative case; `--self-test` is where they live.
FAILURE_CONDITIONS = {
    "F0": "every requirement produces a matrix row",
    "F1": "every requirement reaches a NEED, directly or by an acyclic parent chain",
    "F2": "every requirement has a downstream verification reference",
    "F3": "every NEED/CON/ASM defined in the CONOPS is cited by some requirement",
    "F4": "every parent cited in a trace cell is a requirement in the spine",
    "F5": "every row names an EXECUTED case (owner's addition; a blank is a finding)",
    "F6": "every Test-verified requirement has a demonstrated RED case (HUG-VER-002/B4)",
}


class GenerationFailed(Exception):
    """HUG-VER-001: a specified failure condition means generation fails, not warns."""


#: Which conditions FAIL GENERATION, and which are recorded against the row instead.
#:
#: HUG-VER-001 enumerates its own failure conditions and says each "shall fail matrix
#: generation" — those are F0..F4. F5 is the owner's addition and F6 is HUG-VER-002's,
#: and HUG-VER-002 does not say generation fails: it says the passing RESULT is not
#: accepted until a red case exists. Those two are recorded against the row, loudly,
#: with the row's verdict reflecting them. Collapsing the two classes together would
#: overstate what the record demands in one direction and hide a finding in the other.
GENERATION_FAILING = ("F0", "F1", "F2", "F3", "F4")


def conops_identifiers(conops_text):
    """The NEED/CON/ASM identifiers DEFINED in the CONOPS.

    A definition is the first cell of a body row of a rendered table — not any mention.
    The CONOPS mentions ASM-02 (line 68) and CON-02 (line 158) in running prose, and a
    whole-file regex would read those as definitions. Today it would get the SAME answer,
    because both mentions name identifiers that are also defined in a table — which is
    exactly how that bug ships unnoticed and then fires the day someone mentions an
    identifier that was never defined. Read through the record's own table parser.
    """
    return {cs[0] for cs in _doc_rows(conops_text)
            if cs and CONOPS_ID.fullmatch(cs[0])}


def _reachability(needs, parents):
    """Which requirements reach a NEED. C3's fixed point, over the source.

    Rows citing a NEED seed the reachable set and it propagates backward through parent
    edges until stable. No recursion and no cache, so no traversal order exists for the
    result to depend on, and a cycle is credited only if some row on it independently
    reaches a NEED — which makes that credit genuine, since an acyclic path exists
    through the exit.
    """
    reach = {r: bool(needs.get(r)) for r in parents}
    changed = True
    while changed:
        changed = False
        for r in parents:
            if not reach[r] and any(reach.get(p, False) for p in parents[r] if p != r):
                reach[r] = True
                changed = True
    return reach


def build_matrix(spine, conops_defined, run_record):
    """The whole matrix as a pure function of its three inputs.

    Pure so that every failure condition can be demonstrated by perturbing an input
    rather than by staging a copy of the repository — the live adapter over a pure
    predicate, as ruled at D-010. Returns (rows, findings).
    """
    reqs = hugdefs.requirements_flat(spine)
    ids = [r["id"] for r in reqs]
    findings = []

    # --- upstream: partition each trace cell, because trace_tokens returns four kinds
    needs, parents, cited_conops = {}, {}, set()
    for r in reqs:
        toks = hugdefs.trace_tokens(r["trace"])
        needs[r["id"]] = {t for t in toks if t.startswith("NEED-")}
        parents[r["id"]] = {t for t in toks if t.startswith("HUG-")}
        cited_conops |= {t for t in toks if CONOPS_ID.fullmatch(t)}
    reach = _reachability(needs, parents)

    # --- downstream: what actually ran, indexed by the requirement it declared
    by_req = {}
    for case in run_record["cases"]:
        for q in case.get("verifies") or ():
            by_req.setdefault(q, []).append(case)

    rows = []
    for r in reqs:
        rid = r["id"]
        cases = by_req.get(rid, [])
        executed = [c for c in cases if c["kind"] != "demonstration"]
        demos = [c for c in cases if c["kind"] == "demonstration"]
        passing_demos = [c for c in demos if c["outcome"] == "PASS"]
        red = [c for c in cases if c.get("polarity") == "red"]
        red_declared = [c for c in red if c.get("polarity_source") in
                        ("declared", "class", "method")]
        faulted = [c for c in executed
                   if not verification_run.established(c["outcome"])]
        failed = [c for c in executed if c["outcome"] == "FAIL"]

        # The verdict speaks about the requirement; the fault vocabulary speaks about
        # the run. A requirement whose only cases faulted is NOT verified and is also
        # not refuted — saying either would be a claim this run did not earn.
        established_cases = [c for c in executed
                             if verification_run.established(c["outcome"])]
        instrument = [c for c in executed
                      if c["outcome"] in ("INSTRUMENT_FAULT", "READ_FAULT")]
        if failed:
            verdict = "FAIL"
        elif not cases:
            verdict = "NO_RECORD"
        elif established_cases or passing_demos:
            verdict = "PASS"
        elif instrument:
            # Cases ran and could not observe. Distinct from NO_RECORD, where nothing
            # was attempted — collapsing the two would report a broken fixture as an
            # absence of testing and an absence of testing as a broken fixture.
            verdict = "INSTRUMENT_FAULT"
        else:
            verdict = "NO_RECORD"

        rows.append({
            "id": rid,
            "group": r["group"],
            "methods": r["verification"],
            "trace": r["trace"],
            "needs": sorted(needs[rid]),
            "parents": sorted(parents[rid]),
            "reaches_need": reach.get(rid, False),
            "cases": sorted(c["case_id"] for c in executed),
            "demonstrations": sorted(c["case_id"] for c in demos),
            "red_cases": sorted(c["case_id"] for c in red),
            "red_declared": sorted(c["case_id"] for c in red_declared),
            "red_inferred": sorted(c["case_id"] for c in red
                                   if c.get("polarity_source") == "name"),
            "verdict": verdict,
            "n_cases": len(executed),
        })

    # --- F0: one row per requirement, and no invented rows
    if len(rows) != len(reqs):
        findings.append(("F0", f"{len(rows)} rows for {len(reqs)} requirements"))
    if len(set(ids)) != len(ids):
        dupes = sorted({i for i in ids if ids.count(i) > 1})
        findings.append(("F0", f"duplicate requirement identifiers in the spine: {dupes}"))

    # --- F1: upstream reachability
    stranded = sorted(r["id"] for r in rows if not r["reaches_need"])
    if stranded:
        findings.append(("F1", f"no acyclic path to a NEED: {stranded}"))

    # --- F2 / F5: downstream reference, and that it EXECUTED
    for row in rows:
        if not row["cases"] and not row["demonstrations"]:
            findings.append(("F2", f"{row['id']} has no downstream verification "
                                   f"reference of any kind"))
        elif row["verdict"] in ("NO_RECORD", "INSTRUMENT_FAULT"):
            # The owner's clause. The row names cases, and not one of them established
            # anything about the requirement — either nothing ran (NO_RECORD) or what
            # ran could not observe (INSTRUMENT_FAULT). Both leave the cell empty, and
            # an empty cell is where a matrix stops being evidence and starts being
            # furniture. Named as a finding so it cannot be read as an absence.
            findings.append(("F5", f"{row['id']} names {len(row['cases'])} case(s) but "
                                   f"none established anything ({row['verdict']}): a "
                                   f"blank here is a finding, not an absence"))

    # --- F3: every defined CONOPS identifier cited
    uncited = sorted(conops_defined - cited_conops)
    if uncited:
        findings.append(("F3", f"defined in the CONOPS, cited by no requirement: {uncited}"))
    dangling_conops = sorted(cited_conops - conops_defined)
    if dangling_conops:
        findings.append(("F3", f"cited by a requirement, defined nowhere in the "
                               f"CONOPS: {dangling_conops}"))

    # --- F4: parent citations resolve
    known = set(ids)
    for row in rows:
        bad = sorted(p for p in row["parents"] if p not in known)
        if bad:
            findings.append(("F4", f"{row['id']} cites parent(s) not in the spine: {bad}"))

    # --- F6: a Test-verified requirement owes a demonstrated red case
    for row in rows:
        if "T" in row["methods"] and row["cases"] and not row["red_cases"]:
            findings.append(("F6", f"{row['id']} is Test-verified and every case for it "
                                   f"is green: HUG-VER-002 accepts a passing result only "
                                   f"once a case is demonstrated to fail on violation"))

    return rows, findings


def _verdict_mark(v):
    return {"PASS": "PASS", "FAIL": "**FAIL**",
            "INSTRUMENT_FAULT": "**INSTRUMENT_FAULT**",
            "NO_RECORD": "**NO_RECORD**"}.get(v, v)


def render(rows, findings, run_record, conops_defined):
    meta = run_record["metadata"]
    counts = run_record["counts"]
    out = [
        "# HUGINN traceability matrix (B3, HUG-VER-001)",
        "",
        "<!-- GENERATED by tools/gen_traceability.py. Do not edit. HUG-VER-001: a",
        "     hand-maintained matrix is not accepted as evidence. Regenerate. -->",
        "",
        "Generated by EXECUTING the cases, not by reading the record. Every identifier in",
        "the *executed cases* column ran in the run described below; a row that could name",
        "no executed case is a finding in the table at the foot of this file, never a blank",
        "cell. The distinction matters because a matrix populated from a source scan looks",
        "the same whether or not anything ran.",
        "",
        "## The run this matrix was generated from",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Commit | `{meta['commit']}` |",
        f"| Subject | {meta['commit_subject']} |",
        f"| Tree clean at run | {meta['tree_clean']} |",
        f"| Executed (UTC) | {meta['executed_utc']} |",
        f"| Python / platform | {meta['python']} / {meta['platform']} |",
        f"| Cases executed | {counts['test']} tests, {counts['check']} checks, "
        f"{counts['mutation']} red/green mutation cases |",
        f"| Archived demonstrations read | {counts['demonstration']} |",
        "",
        "## Matrix",
        "",
        "One row per requirement in `defs/requirements.yaml`, in record order — the record's",
        "order is not sorted, and sorting it here would silently reorder the record.",
        "",
        "| Requirement | V | Upstream | Downstream (executed) | Red case | Verdict |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        up = ", ".join(r["needs"]) or ("via " + ", ".join(r["parents"])
                                       if r["parents"] else "—")
        n = len(r["cases"])
        down = f"{n} case(s)" if n else ""
        if r["demonstrations"]:
            down += (" + " if down else "") + f"{len(r['demonstrations'])} demo(s)"
        out.append(f"| `{r['id']}` | {'/'.join(r['methods'])} | {up} | {down or '—'} | "
                   f"{len(r['red_cases']) or '—'} | {_verdict_mark(r['verdict'])} |")

    out += ["", "## Per-requirement executed cases", "",
            "The case identifiers themselves, so a reader can re-run any single row.", ""]
    for r in rows:
        out.append(f"### `{r['id']}` — {'/'.join(r['methods'])} — {_verdict_mark(r['verdict'])}")
        out.append("")
        out.append(f"- Trace cell: `{r['trace']}`")
        out.append(f"- Reaches a NEED: {r['reaches_need']}"
                   + (f" (via {', '.join(r['parents'])})" if not r["needs"] else ""))
        if r["cases"]:
            out.append(f"- Executed cases ({len(r['cases'])}):")
            for c in r["cases"]:
                out.append(f"  - `{c}`")
        if r["demonstrations"]:
            out.append("- Demonstrations:")
            for c in r["demonstrations"]:
                out.append(f"  - `{c}`")
        if not r["cases"] and not r["demonstrations"]:
            out.append("- **No executed case. This is a finding, recorded below.**")
        out.append("")

    out += ["## Findings", ""]
    if findings:
        out += ["Generation FAILED. Under HUG-VER-001 each of these is a failure "
                "condition, not a warning.", "",
                "| Condition | Finding |", "|---|---|"]
        out += [f"| {c} | {m} |" for c, m in findings]
    else:
        out.append("None. Every requirement produces a row, reaches a NEED, names an "
                   "executed case, and — where Test-verified — names a red case; every "
                   f"one of the {len(conops_defined)} CONOPS identifiers is cited.")
        out += ["",
                "**This clean result is not by itself evidence the checks work.** Every "
                "failure condition above has zero naturally occurring instances in this "
                "record, so a generator with all of them stubbed would print this same "
                "section. What makes it evidence is `--self-test`, which demonstrates "
                "each condition failing generation on a synthesized input, and which runs "
                "in the gate."]
    out += ["", "## Conditions enforced", "", "| # | Condition |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in FAILURE_CONDITIONS.items()]
    out.append("")
    return "\n".join(out)


def load_inputs(repo=REPO, run_record=None):
    spine = hugdefs.load_requirements()
    conops = (repo / "docs" / "conops.md").read_text(encoding="utf-8")
    if run_record is None:
        run_record = verification_run.collect(repo)
    return spine, conops_identifiers(conops), run_record


def generate(repo=REPO, run_record=None, check_only=False):
    spine, defined, record = load_inputs(repo, run_record)
    rows, findings = build_matrix(spine, defined, record)
    text = render(rows, findings, record, defined)
    if check_only:
        old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        return rows, findings, text, old
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    return rows, findings, text, None


# ---------------------------------------------------------------------------
# The negative case per failure edge (HUG-VER-001's last sentence, B4).
#
# Each mutation perturbs an INPUT and requires the named condition to fire. Kept
# beside the conditions they exercise so a condition added without a red case is
# visible as a missing key rather than as a silent gap.
# ---------------------------------------------------------------------------
def _strip_need(spine, rid):
    for g in spine["groups"]:
        for r in g["requirements"]:
            if r["id"] == rid:
                r["trace"] = re.sub(r"\bNEED-\d{2}\b", "", r["trace"]).strip("; ")
    return spine


def _set_trace(spine, rid, trace):
    for g in spine["groups"]:
        for r in g["requirements"]:
            if r["id"] == rid:
                r["trace"] = trace
    return spine


def _drop_requirement_cases(record, rid):
    for c in record["cases"]:
        if rid in (c.get("verifies") or ()):
            c["verifies"] = [q for q in c["verifies"] if q != rid]
    return record


def _unexecute(record, rid):
    """Leave the references, remove the EXECUTION.

    F5 is the owner's clause — a row that names references but no executed case. It is
    NOT the same as F2, and deleting the cases outright tests F2 twice while leaving F5
    unexercised. The shape that actually produces F5 is a suite that collected the cases
    and skipped them, which is what a broken fixture or a guarded import does.
    """
    for c in record["cases"]:
        if rid in (c.get("verifies") or ()):
            c["outcome"] = "NO_RECORD"
            c["detail"] = "skipped"
    return record


def _make_all_green(record, rid):
    for c in record["cases"]:
        if rid in (c.get("verifies") or ()) and c.get("polarity") == "red":
            c["polarity"] = "green"
    return record


MUTATIONS = {
    "F0": [("a duplicated requirement identifier in the spine",
            lambda s, d, r: (_dup(s), d, r))],
    "F1": [("a requirement stranded with no NEED and no parent",
            lambda s, d, r: (_set_trace(s, "HUG-SYS-003", "Method rule"), d, r)),
           ("a two-row parent cycle with no NEED exit",
            lambda s, d, r: (_set_trace(_set_trace(s, "HUG-SYS-003", "HUG-SYS-004"),
                                        "HUG-SYS-004", "HUG-SYS-003"), d, r)),
           ("the one row that needs the chain, with its parent edge removed",
            lambda s, d, r: (_set_trace(s, "HUG-EPS-004", "G001 F-03"), d, r))],
    "F2": [("a requirement with no downstream reference at all",
            lambda s, d, r: (s, d, _drop_requirement_cases(r, "HUG-CMD-002")))],
    "F3": [("a CONOPS identifier cited by nobody",
            lambda s, d, r: (_strip_conops(s, "ASM-02"), d, r)),
           ("a requirement citing a CONOPS identifier that is not defined",
            lambda s, d, r: (_set_trace(s, "HUG-SYS-003", "NEED-04; CON-99"), d, r))],
    "F4": [("a trace cell citing a parent that is not a requirement",
            lambda s, d, r: (_set_trace(s, "HUG-EPS-004", "HUG-ZZZ-999"), d, r))],
    "F5": [("a requirement whose cases were collected but never executed",
            lambda s, d, r: (s, d, _unexecute(r, "HUG-OPS-002"))),
           ("the whole suite skipped: every row still names its cases",
            lambda s, d, r: (s, d, _unexecute_all(r)))],
    "F6": [("a Test-verified requirement whose red case turned green",
            lambda s, d, r: (s, d, _make_all_green(r, "HUG-CMD-002")))],
}

GREEN_CASES = [
    ("the record as it stands", lambda s, d, r: (s, d, r)),
    ("a requirement reaching its NEED only through a parent chain (HUG-EPS-004)",
     lambda s, d, r: (s, d, r)),
    ("a CONOPS identifier mentioned in prose as well as defined in a table",
     lambda s, d, r: (s, d, r)),
]


def _unexecute_all(record):
    for c in record["cases"]:
        if c["kind"] != "demonstration":
            c["outcome"] = "NO_RECORD"
    return record


def _dup(spine):
    g = spine["groups"][0]
    g["requirements"].append(dict(g["requirements"][0]))
    return spine


def _strip_conops(spine, token):
    for g in spine["groups"]:
        for r in g["requirements"]:
            r["trace"] = re.sub(rf"\b{re.escape(token)}\b", "", r["trace"]).strip("; ")
    return spine


def self_test(repo=REPO):
    import copy
    print("SELF-TEST (HUG-VER-001 last sentence, B4): every failure condition must be\n"
          "demonstrated to FAIL generation. None of them occurs naturally in this record —\n"
          "all 38 requirements reach a NEED and all 11 CONOPS identifiers are cited — so a\n"
          "generator with every condition stubbed would emit an identical clean matrix.\n"
          "These are the cases that tell the two apart.\n")
    spine0, defined0, record0 = load_inputs(repo)

    rows, baseline = build_matrix(copy.deepcopy(spine0), set(defined0),
                                  copy.deepcopy(record0))
    failed = []
    base_set = set(baseline)
    print(f"[BASELINE] {len(rows)} rows, {len(baseline)} standing finding(s): "
          f"{sorted({c for c, _m in baseline})}. A mutation counts as CAUGHT only when "
          f"it adds a finding that was NOT already standing; otherwise the record's own "
          f"open findings would certify every red case for free.")

    missing = sorted(set(FAILURE_CONDITIONS) - set(MUTATIONS))
    if missing:
        print(f"[NO-RED-CASE] conditions with no negative case: {missing}")
        failed.extend(missing)

    for cond, cases in MUTATIONS.items():
        for j, (label, mutate) in enumerate(cases, 1):
            s, d, r = mutate(copy.deepcopy(spine0), set(defined0),
                             copy.deepcopy(record0))
            try:
                _, f = build_matrix(s, d, r)
                fired = {c for c, _m in f}
                f = set(f)
            except Exception as exc:
                # A condition "demonstrated" by a crash demonstrates only that the
                # generator dies on the input — OF-008's shape, and refused here.
                print(f"[CRASHED] {cond}.m{j} ({label}) raised "
                      f"{type(exc).__name__}: {exc}")
                failed.append(f"{cond}.m{j}")
                continue
            new = {c for c in f if c not in base_set}
            fired_new = {c for c, _m in new}
            if cond in fired_new:
                print(f"[CAUGHT] {cond}.m{j} ({label})")
            else:
                print(f"[MISSED] {cond}.m{j} ({label}) — new findings: "
                      f"{sorted(fired_new) or 'none'}; all fired: {sorted(fired)}")
                failed.append(f"{cond}.m{j}")

    total = sum(len(v) for v in MUTATIONS.values())
    print(f"\nSELF-TEST RESULT: {total - len([f for f in failed if '.' in f])}/{total} "
          f"negative cases fire their own condition"
          + (f"; FAILED: {failed}" if failed
             else "; every failure condition demonstrated to fail generation"))
    return 1 if failed else 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="regenerate and compare; write nothing")
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--run-record", metavar="PATH",
                    help="reuse a run record instead of executing (for --check only)")
    args = ap.parse_args(argv)
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, OSError):  # pragma: no cover
        pass

    if args.self_test:
        return self_test()

    record = None
    if args.run_record:
        record = json.loads(Path(args.run_record).read_text(encoding="utf-8"))
    try:
        rows, findings, text, old = generate(run_record=record, check_only=args.check)
    except verification_run.EmptyRun as exc:
        print(f"[INSTRUMENT_FAULT] the matrix was not generated: {exc}")
        return 2

    if args.check and old is not None and old != text:
        diff = difflib.unified_diff(old.splitlines(), text.splitlines(),
                                    "committed", "regenerated", lineterm="", n=1)
        print("\n".join(list(diff)[:60]))
        print(f"[FAIL] {OUT.relative_to(REPO).as_posix()} is not what the record "
              f"generates. Regenerate; do not hand-edit.")
        return 1

    verdicts = {}
    for r in rows:
        verdicts[r["verdict"]] = verdicts.get(r["verdict"], 0) + 1
    print(f"{len(rows)} requirements: " +
          ", ".join(f"{v} {k}" for k, v in sorted(verdicts.items())))
    if findings:
        print(f"\nGENERATION FAILED — {len(findings)} finding(s):")
        for cond, msg in findings:
            print(f"  [{cond}] {msg}")
        return 1
    print(f"wrote {OUT.relative_to(REPO).as_posix()}" if not args.check
          else "matrix matches the record")
    return 0


if __name__ == "__main__":
    sys.exit(main())
