#!/usr/bin/env python3
"""The verification report (B5, HUG-VER-003) and the ITEM-5 evidence chain.

    python tools/gen_verification_report.py            execute, write both documents
    python tools/gen_verification_report.py --check    regenerate and diff, write nothing
    python tools/gen_verification_report.py --self-test  the negative cases

HUG-VER-003: "The verification report shall be generated by executing all checkers
against the release candidate and shall record pass/fail per requirement with run
metadata." Every word of that is load-bearing:

  BY EXECUTING      — the report is rendered from tools/verification_run.py's record,
                      never from the spec. A report written by reading requirements
                      would say the same thing on a machine where nothing ran.
  ALL CHECKERS      — both record checkers, both self-tests, the whole unittest suite.
                      The run refuses to return a record that collected fewer cases
                      than this build carries, so a partial run cannot be reported as
                      a clean one.
  AGAINST THE RC    — the commit is named, and whether the tree was clean when the run
                      happened is named beside it. A report generated from a dirty tree
                      that claims a commit is a report about something that was never
                      committed.
  PASS/FAIL PER REQ — per requirement, not per suite. A suite total tells a reader that
                      something passed, not that any particular requirement did.
  RUN METADATA      — when, on what, with which interpreter.

THE VOCABULARY HOLDS THROUGHOUT. PASS and FAIL are statements about the SUBJECT. A
requirement is PASS because a case observed it and it held. INSTRUMENT_FAULT, READ_FAULT
and NO_RECORD are statements about the OBSERVER or the RUN: the case could not look, or
never looked, and the requirement's status is therefore NOT ESTABLISHED. This report
never counts a fault as a failure of the subject and never counts it as a pass. That
distinction was ruled at D-011 for the evidence harness and D-012 for the monitor, and
it is the same distinction here because it is the same mistake being guarded against.

THE EVIDENCE CHAIN'S EXECUTION STATUS IS NOT AUTHORED. defs/evidence_chain.yaml holds
the direction claims — judgements about the record, which belong in the record. Whether
each named case EXISTS and EXECUTED comes from the run, because a chain that asserted its
own execution status would be exactly the artifact it exists to prevent. A claimed case
absent from the run record is rendered as a finding, never dropped.
"""
