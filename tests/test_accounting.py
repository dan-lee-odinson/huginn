#!/usr/bin/env python3
"""Command accounting: exactly-once, the reset epoch as the SOLE exception, and the
one-frame visibility bound.

Owner standing instruction for Phase 2. These three are what make the operator's
verification step real:

  Every procedure step that sends a command verifies it by counter delta plus the
  affected telemetry point (PROC-001, Dictionary Sec. 2). That step is only sound if
  a delta of exactly one means exactly one command was accounted - so exactly-once is
  asserted for every command, at both polarities, including the unknown-opcode path.

  CMD_SYS_RESET is the sole exception, and "sole" is asserted rather than assumed:
  the test walks all five commands and requires that exactly one of them breaks delta
  arithmetic. An operator who expects a delta after a reset would read a successful
  reset as a failed one - so the epoch (ACC = 1, REJ = 0) is checked from several
  prior counter states, including after wrap-relevant counts.

  The visibility bound (HUG-CMD-007, no later than the next housekeeping frame) is
  what bounds how long the operator waits before declaring the command lost. It is
  asserted on the frame generated by the very tick the command arrives on.
"""
import unittest

from harness import set_soc, spacecraft, tlm_defs

COUNTERS = ("CDH_CMD_ACC_CNT", "CDH_CMD_REJ_CNT")


def counters(sim):
    return sim.cdh.acc_count, sim.cdh.rej_count


class TestExactlyOnce(unittest.TestCase):
    """HUG-CMD-007: each received command increments exactly one counter by one."""
    verifies = ("HUG-CMD-007",)

    def _cases(self):
        """Every command at an accepting and a rejecting polarity, plus an opcode the
        spacecraft cannot identify at all."""
        return [
            ("CMD_PLD_SET_STATE accept", "CMD_PLD_SET_STATE", {"state": "ON"}, 100.0, True),
            ("CMD_PLD_SET_STATE inhibit", "CMD_PLD_SET_STATE", {"state": "ON"}, 10.0, False),
            ("CMD_PLD_SET_STATE arg", "CMD_PLD_SET_STATE", {"state": "MAYBE"}, 100.0, False),
            ("CMD_PLD_SET_RATE arg-low", "CMD_PLD_SET_RATE", {"rate": 0.05}, 100.0, False),
            ("CMD_PLD_SET_RATE arg-high", "CMD_PLD_SET_RATE", {"rate": 10.5}, 100.0, False),
            ("CMD_PLD_SET_RATE payload-off", "CMD_PLD_SET_RATE", {"rate": 5.0}, 100.0, False),
            ("CMD_SAFE_ENTER accept", "CMD_SAFE_ENTER", {}, 100.0, True),
            ("CMD_SAFE_ENTER accept-in-safe", "CMD_SAFE_ENTER", {}, 5.0, True),
            ("CMD_MODE_SET accept", "CMD_MODE_SET", {"target": "NOMINAL"}, 100.0, True),
            ("CMD_MODE_SET arg", "CMD_MODE_SET", {"target": "SAFE"}, 100.0, False),
            ("CMD_MODE_SET inhibit", "CMD_MODE_SET", {"target": "NOMINAL"}, 30.0, False),
            ("unknown mnemonic", "CMD_NOT_A_COMMAND", {}, 100.0, False),
        ]

    def test_every_command_advances_exactly_one_counter_by_exactly_one(self):
        for label, mnemonic, args, soc, expect_accept in self._cases():
            with self.subTest(case=label):
                sim = set_soc(spacecraft(), soc)
                before_acc, before_rej = counters(sim)
                accepted, reason = sim.cdh.receive(mnemonic, args)
                after_acc, after_rej = counters(sim)
                self.assertEqual(accepted, expect_accept,
                                 f"{label}: expected accepted={expect_accept}, "
                                 f"got {accepted} (reason {reason})")
                d_acc, d_rej = after_acc - before_acc, after_rej - before_rej
                self.assertEqual((d_acc + d_rej), 1,
                                 f"{label}: {d_acc + d_rej} counter increments, "
                                 f"expected exactly 1")
                if expect_accept:
                    self.assertEqual((d_acc, d_rej), (1, 0))
                    self.assertEqual(reason, "NONE")
                else:
                    self.assertEqual((d_acc, d_rej), (0, 1))
                    self.assertIn(reason, ("UNKNOWN_OPCODE", "ARG_RANGE", "MODE_INHIBIT"))

    def test_an_undefined_wire_opcode_is_accounted_and_reasoned(self):
        """HUG-CMD-001: an opcode the spacecraft cannot identify is still a command
        it received. Silently dropping it would leave the ground waiting for a delta
        that never comes, and PROC-003 would be entered for a fault that is really a
        mis-built command."""
        sim = spacecraft()
        defined = set(sim.cdh.opcodes)
        undefined = max(defined) + 1
        before_acc, before_rej = counters(sim)
        accepted, reason = sim.cdh.receive_opcode(undefined)
        self.assertFalse(accepted)
        self.assertEqual(reason, "UNKNOWN_OPCODE")
        self.assertEqual(counters(sim), (before_acc, before_rej + 1))
        self.assertEqual(sim.cdh.rej_reason, "UNKNOWN_OPCODE")

    def test_counters_are_uint16_and_wrap(self):
        """Dictionary Sec. 1: uint16 (wraps). Asserted so the delta a procedure reads
        stays valid across the wrap rather than going hugely negative."""
        sim = set_soc(spacecraft(), 100.0)
        sim.cdh.acc_count = 65535
        sim.cdh.receive("CMD_SAFE_ENTER", {})
        self.assertEqual(sim.cdh.acc_count, 0, "accept counter must wrap at uint16")


class TestResetEpochIsTheSoleException(unittest.TestCase):
    """HUG-CMD-005 / Dictionary Sec. 2, ledger item 6."""
    verifies = ("HUG-CMD-005", "HUG-CMD-007")

    def test_reset_produces_the_acc1_rej0_epoch_from_any_prior_state(self):
        for prior in ((0, 0), (1, 0), (7, 3), (65535, 65535), (100, 65000)):
            with self.subTest(prior_counters=prior):
                sim = set_soc(spacecraft(), 100.0)
                sim.cdh.acc_count, sim.cdh.rej_count = prior
                sim.cdh.rej_reason = "ARG_RANGE"
                accepted, reason = sim.cdh.receive("CMD_SYS_RESET", {})
                self.assertTrue(accepted)
                self.assertEqual(reason, "NONE")
                self.assertEqual(counters(sim), (1, 0),
                                 "the post-reset counter epoch must read ACC=1, REJ=0 "
                                 "regardless of what the counters held before")
                self.assertEqual(sim.cdh.rej_reason, "NONE",
                                 "a zeroed reject counter alongside a non-NONE last "
                                 "reject reason would be self-contradictory")

    def test_reset_is_the_only_command_that_breaks_delta_arithmetic(self):
        """'Sole exception' asserted, not assumed: walk all five commands and require
        that exactly one of them fails to be a +1 delta on a non-zero start."""
        breaks = []
        for command in tlm_defs()["commands"]:
            mnemonic = command["mnemonic"]
            args = {"CMD_PLD_SET_STATE": {"state": "ON"},
                    "CMD_PLD_SET_RATE": {"rate": 2.0},
                    "CMD_MODE_SET": {"target": "NOMINAL"}}.get(mnemonic, {})
            sim = set_soc(spacecraft(), 100.0)
            if mnemonic == "CMD_PLD_SET_RATE":
                sim.eps.state.payload_on = True
            sim.cdh.acc_count, sim.cdh.rej_count = 10, 4
            before = counters(sim)
            sim.cdh.receive(mnemonic, args)
            after = counters(sim)
            delta = (after[0] - before[0]) + (after[1] - before[1])
            if delta != 1:
                breaks.append(mnemonic)
        self.assertEqual(breaks, ["CMD_SYS_RESET"],
                         "exactly one command may break delta arithmetic, and it must "
                         f"be CMD_SYS_RESET; got {breaks}")

    def test_reset_preserves_state_of_charge(self):
        """HUG-CMD-005. A reset that re-initialised the battery would make every
        post-reset power assessment a fiction."""
        for soc in (5.0, 22.5, 70.0, 100.0):
            sim = set_soc(spacecraft(), soc)
            before_wh = sim.eps.state.energy_wh
            sim.cdh.receive("CMD_SYS_RESET", {})
            self.assertEqual(sim.eps.state.energy_wh, before_wh,
                             f"CMD_SYS_RESET changed stored energy at SoC {soc}%")

    def test_reset_clears_the_latched_generation_halt(self):
        """HUG-EPS-004(c) / HUG-CMD-005: the fault latches until reset clears it, and
        frame generation resumes with the counter epoch."""
        sim = set_soc(spacecraft(), 100.0)
        sim.cdh.halt_hk_generation()
        self.assertIsNone(sim.cdh.generate_frame(0), "frames must stop while halted")
        sim.cdh.receive("CMD_SYS_RESET", {})
        frame = sim.cdh.generate_frame(1)
        self.assertIsNotNone(frame, "frame generation must resume after reset")
        self.assertEqual(frame["CDH_CMD_ACC_CNT"], 1)
        self.assertEqual(frame["CDH_CMD_REJ_CNT"], 0)


class TestOneFrameVisibilityBound(unittest.TestCase):
    """HUG-CMD-007: the increment plus any commanded effect is visible no later than
    the next housekeeping frame."""
    verifies = ("HUG-CMD-007",)

    def _visibility_cases(self):
        return [
            ("payload on", "CMD_PLD_SET_STATE", {"state": "ON"}, 100.0,
             "PLD_STATE", "ON"),
            ("payload off", "CMD_PLD_SET_STATE", {"state": "OFF"}, 100.0,
             "PLD_STATE", "OFF"),
            ("safe entry", "CMD_SAFE_ENTER", {}, 100.0, "EPS_MODE", "SAFE"),
            ("mode set", "CMD_MODE_SET", {"target": "LOW_POWER"}, 100.0,
             "EPS_MODE", "LOW_POWER"),
        ]

    def test_effect_and_increment_appear_in_the_frame_of_the_same_tick(self):
        for label, mnemonic, args, soc, point, expected in self._visibility_cases():
            with self.subTest(case=label):
                sim = spacecraft(duration_s=10,
                                 commands=[{"t_s": 3, "mnemonic": mnemonic,
                                            "args": args}])
                set_soc(sim, soc)
                frames = []
                while sim.t_s < 10:
                    frames.append(sim.step())
                # The command is sent on t_s = 3, which is the 4th frame (index 3).
                sent_frame = frames[3]
                self.assertIsNotNone(sent_frame)
                self.assertEqual(sent_frame[point], expected,
                                 f"{label}: the commanded effect was not visible in "
                                 f"the frame generated on the tick it was sent")
                self.assertEqual(sent_frame["CDH_CMD_ACC_CNT"], 1,
                                 f"{label}: the accept counter had not advanced in "
                                 f"that frame")
                self.assertEqual(frames[2]["CDH_CMD_ACC_CNT"], 0,
                                 f"{label}: the counter advanced BEFORE the command "
                                 f"was sent")

    def test_rate_command_effect_is_visible_within_one_frame(self):
        sim = spacecraft(duration_s=10, initial={"soc_pct": 100.0},
                         commands=[{"t_s": 2, "mnemonic": "CMD_PLD_SET_STATE",
                                    "args": {"state": "ON"}},
                                   {"t_s": 4, "mnemonic": "CMD_PLD_SET_RATE",
                                    "args": {"rate": 7.5}}])
        frames = [sim.step() for _ in range(10)]
        self.assertEqual(frames[4]["PLD_RATE"], 7.5)
        self.assertEqual(frames[4]["CDH_CMD_ACC_CNT"], 2)

    def test_rejection_reason_is_visible_within_one_frame(self):
        sim = spacecraft(duration_s=10, initial={"soc_pct": 10.0},
                         commands=[{"t_s": 3, "mnemonic": "CMD_PLD_SET_STATE",
                                    "args": {"state": "ON"}}])
        frames = [sim.step() for _ in range(10)]
        self.assertEqual(frames[3]["CDH_CMD_REJ_CNT"], 1)
        self.assertEqual(frames[3]["CDH_REJ_REASON"], "MODE_INHIBIT")


if __name__ == "__main__":
    unittest.main(verbosity=2)
